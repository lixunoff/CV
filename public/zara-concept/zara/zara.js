    if (!s) {
      s = { id: 's' + Date.now(), title: titleFrom(text), tag: 'guide', updated: Date.now(), messages: [] };
      sessions.push(s);
      activeId = s.id;
      threadInner.innerHTML = '';
      title.textContent = s.title;
      boxInput.placeholder = 'Ask a follow-up…';
    }
    const key = route(text);
    s.tag = s.messages.length ? s.tag : ANSWERS[key].tag;
    s.messages.push({ role: 'user', text, t: Date.now() });
    s.updated = Date.now();
    openSessionId = s.id;
    save();
    renderList();

    threadInner.querySelectorAll('.z-followups').forEach((f) => f.remove());
    if (threadInner.querySelector('.z-welcome')) threadInner.innerHTML = '';
