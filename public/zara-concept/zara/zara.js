  function stream(s, key) {
    const a = ANSWERS[key];
    const msg = { role: 'ai', key, t: Date.now() };
    const el = document.createElement('div');
    el.className = 'z-msg z-msg--ai is-thinking';
    el.innerHTML = `${symbol('xs')}<div class="z-ai-body"><div class="z-ai-name z-meta"><span class="z-meta-label">Thinking…</span></div><div class="z-steps-slot"></div><div class="z-ai-text"></div></div>`;
    threadInner.appendChild(el);
    markMode($('.z-symbol', el), 'think'); // Zara is thinking: full motion until the answer is done
    const slot = $('.z-steps-slot', el), body = $('.z-ai-text', el), wrap = $('.z-ai-body', el);
    const timers = [];
    let cancelled = false;
    const later = (fn, ms) => { const t = setTimeout(fn, ms); timers.push(t); return t; };
    const scroll = () => { thread.scrollTop = thread.scrollHeight; };

    setBusy(true);
    streaming = { cancel() {
      cancelled = true; timers.forEach(clearTimeout);
      msg.stopped = true; finish();
    } };

    // tool progress
    let i = 0;
    const tick = () => {
      slot.innerHTML = stepsHTML(a.steps.slice(0, i + 1), i, false);
      scroll();
      if (i < a.steps.length - 1) { i++; later(tick, 650 + Math.random() * 350); }
      else later(() => { slot.innerHTML = stepsHTML(a.steps, a.steps.length, false); later(() => writeBlocks(0), 300); }, 700);
    };
    tick();

    // streamed blocks: text word by word, rich blocks appear whole
    function writeBlocks(bi) {
      if (cancelled) return;
      if (bi >= a.blocks.length) return finish();
      const b = a.blocks[bi];
      const html = blockHTML(b);
      if (b.p || b.ol) {
        const holder = document.createElement('div');
        holder.innerHTML = html;
        const node = holder.firstElementChild;
        body.appendChild(node);
        typeInto(node, () => writeBlocks(bi + 1));
      } else {
        body.insertAdjacentHTML('beforeend', html);
        body.lastElementChild.style.animation = 'z-in .35s var(--z-ease) both';
        scroll();
        later(() => writeBlocks(bi + 1), 260);
      }
    }

    function typeInto(node, done) {
      // collect text nodes, reveal them progressively while keeping inline markup
      const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
      const texts = [];
      while (walker.nextNode()) texts.push(walker.currentNode);
      const full = texts.map((t) => t.nodeValue);
      texts.forEach((t) => { t.nodeValue = ''; });
      const hidden = [...node.querySelectorAll('.z-cite, li')];
      hidden.forEach((h) => { h.style.visibility = 'hidden'; });
      const caret = document.createElement('span');
      caret.className = 'z-caret';
      let ti = 0, ci = 0;
      const step = () => {
        if (cancelled) { caret.remove(); return; }
        if (ti >= texts.length) { caret.remove(); hidden.forEach((h) => { h.style.visibility = ''; }); return later(done, 120); }
        const t = texts[ti], src = full[ti];
        const li = t.parentElement.closest('li'); if (li) li.style.visibility = '';
        const n = Math.min(src.length, ci + 3 + Math.floor(Math.random() * 5));
        t.nodeValue = src.slice(0, n); ci = n;
        t.parentNode.insertBefore(caret, t.nextSibling);
        if (ci >= src.length) {
          const cite = t.nextSibling && t.nextSibling.nextSibling;
          if (cite && cite.classList && cite.classList.contains('z-cite')) cite.style.visibility = '';
          ti++; ci = 0;
        }
        scroll();
        later(step, 18 + Math.random() * 22);
      };
      step();
    }

    function finish() {
      if (finish.done) return; finish.done = true;
      el.classList.remove('is-thinking');
      // the steps stay open while the answer is written, then fold away under "Show sources"
      const live = slot.querySelector('.z-steps');
      const settle = () => {
        if (!msg.stopped) slot.innerHTML = foldedSteps(a);
        $('.z-meta', el).outerHTML = metaHTML(msg); // "Answered … · Show sources" arrives once the steps have folded
        const link = $('.z-meta-link', el);
        if (link && !reduced()) link.animate([{ opacity: 0 }, { opacity: 1 }], { duration: 250, easing: 'ease-out' });
      };
      if (live && !msg.stopped && !reduced()) {
        live.style.overflow = 'hidden';
        live.animate([{ height: live.offsetHeight + 'px', opacity: 1 }, { height: '0px', opacity: 0, marginBottom: '0px' }],
          { duration: 360, easing: 'cubic-bezier(.4, 0, .2, 1)', fill: 'forwards' }).onfinish = settle;
      } else settle();
      // the mark settles onto its static outline first, then hands over to the small finished mark
      markMode($('.z-symbol', el), 'off', () => { const sym = $('.z-symbol', el); if (sym) sym.outerHTML = spark(); el.classList.add('is-done'); });
      $('.z-caret', el)?.remove();
      el.querySelectorAll('[style*="visibility"]').forEach((h) => { h.style.visibility = ''; });
      if (msg.stopped) {
        slot.innerHTML = '';
        body.insertAdjacentHTML('beforeend', '<p><i style="color:var(--z-muted)">Stopped.</i></p>');
      } else {
        wrap.insertAdjacentHTML('beforeend', sourcesHTML(a));
      }
      wrap.insertAdjacentHTML('beforeend', actionsHTML(msg) + (msg.stopped || !auth ? '' : followHTML(a)));
      s.messages.push(msg);
      s.updated = Date.now();
      save(); renderList();
      streaming = null;
      setBusy(false);
      if (!auth) gateAfter();
      scroll();
    }
  }

